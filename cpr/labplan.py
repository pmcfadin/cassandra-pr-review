"""Generate an easy-db-lab plan.md for a PR: build the merge-base and the PR head, run the workload that fits
the change, compare. Deterministic (no model call). The plan is text only: nothing here runs easy-db-lab,
provisions anything, or touches the network."""

import json
import os
import re

from cpr import VERSION, paths
from cpr.checks import Context
from cpr.checks.ci import upgrade_sensitive_files
from cpr.checks.compat import touched_surfaces

CONFIG = os.path.join(os.path.dirname(__file__), "config", "labplan.json")
PKG = "src/java/org/apache/cassandra/"
EDB = "$EDB"
SAFE_IDENT = re.compile(r"^[A-Za-z0-9._/-]+$")
SHA40 = re.compile(r"^[0-9a-f]{40}$")
TITLE_KEEP = re.compile(r"[^A-Za-z0-9 \-_.:()]")
JIRA_KEY = re.compile(r"^[A-Z][A-Z0-9]*-\d+$")

BANNER = ("> **Not run.** Generated by cassandra-pr-review {version} from the PR diff on {date}. No cluster was created, "
          "no AWS resource touched, and no command below was executed. Commands are checked against "
          "`easy-db-lab commands` (version {edb}) only for spelling. Review before running.")


def load_config(path=CONFIG):
    with open(path) as f:
        return json.load(f)


def sanitise_title(text, limit=80):
    """Keep alphanumerics, spaces and -_.:() only, collapse whitespace, cut at `limit` characters."""
    s = TITLE_KEEP.sub("", str(text or ""))
    s = re.sub(r"\s+", " ", s).strip()
    return s[:limit].strip()


def _none(reason):
    return {"status": "none", "reason": reason, "scenarios": [], "dropped": [], "markdown": "", "filename": None}


def no_plan_reason(bundle, cfg):
    """Why this PR gets no plan, or None when it should."""
    files = bundle.get("files", [])
    if not files:
        return "the PR changes no files"
    names = [f["path"] for f in files]
    if all(paths.is_doc(p) for p in names):
        return "documentation-only change"
    server = [f for f in files if f["path"].startswith("src/java/") and not paths.is_test(f["path"]) and paths.counted(f)]
    if not server:
        if all(paths.is_test(p) or paths.is_test_resource(p) for p in names):
            return "tests-only change"
        if all(re.match(r"^(lib/|\.build/(build-resolve|parent-pom-template|cassandra-deps-template|cassandra-build-deps-template)\.xml)", p)
               for p in names):
            return "dependency change"
        if all(paths.is_build(p) for p in names):
            return "build or CI change"
        if all(paths.is_generated(p) for p in names):
            return "generated files only"
        return "no server code under src/java changed (tooling, configuration or Python only)"
    if len(server) > cfg["max_prod_files"]:
        return (f"{len(server)} production files changed (limit {cfg['max_prod_files']}): an A-B run would not isolate "
                "any one change; split the PR")
    return None


def _matches(rule, path, sensitive, surface_paths, text):
    rel = path[len(PKG):] if path.startswith(PKG) else None
    hit = bool(rel is not None and any(rel.startswith(p) for p in rule.get("prefixes", [])))
    hit = hit or any(re.search(rx, path) for rx in rule.get("regex", []))
    hit = hit or (rule.get("upgrade_sensitive") and path in sensitive)
    hit = hit or any(path in surface_paths.get(s, ()) for s in rule.get("surfaces", []))
    if not hit:
        return False
    if rule.get("keywords") and not re.search(rule["keywords"], text, re.I):
        return False
    if rule.get("exclude_keywords") and re.search(rule["exclude_keywords"], text, re.I):
        return False
    return True


def select(bundle, cfg):
    """Rank scenarios from the rules. Returns (chosen, dropped); each is {id, rules, priority, lines, files, paths}."""
    ctx = Context(bundle)
    sensitive = set(upgrade_sensitive_files(ctx))
    surface_paths = touched_surfaces([f["path"] for f in bundle["files"]])
    ticket = (bundle.get("jira") or {}).get("ticket") or {}
    text = f"{bundle['pr'].get('title', '')} {ticket.get('summary', '')}"
    prod = [f for f in bundle["files"] if f["path"].startswith("src/java/") and not paths.is_test(f["path"])
            and paths.counted(f)]
    by_scn = {}
    for rule in cfg["rules"]:
        covered = [f for f in prod if _matches(rule, f["path"], sensitive, surface_paths, text)]
        lines = sum(f["additions"] + f["deletions"] for f in covered)
        if not covered or lines < rule["min_lines"]:
            continue
        s = by_scn.setdefault(rule["scenario"], {"id": rule["scenario"], "rules": [], "priority": 0, "files": {}})
        s["rules"].append(rule["id"])
        s["priority"] = max(s["priority"], rule["priority"])
        for f in covered:
            s["files"][f["path"]] = f["additions"] + f["deletions"]
    ranked = []
    for s in by_scn.values():
        ranked.append({"id": s["id"], "rules": s["rules"], "priority": s["priority"], "lines": sum(s["files"].values()),
                       "files": len(s["files"]),
                       "paths": [p for p, _ in sorted(s["files"].items(), key=lambda kv: (-kv[1], kv[0]))]})
    ranked.sort(key=lambda s: (-s["priority"], -s["lines"], s["id"]))
    if not ranked:
        top = sorted(prod, key=lambda f: (-(f["additions"] + f["deletions"]), f["path"]))
        ranked = [{"id": "smoke", "rules": ["default-smoke"], "priority": 0, "lines": sum(f["additions"] + f["deletions"] for f in prod),
                   "files": len(prod), "paths": [f["path"] for f in top]}]
    return ranked[:cfg["max_scenarios"]], ranked[cfg["max_scenarios"]:]


